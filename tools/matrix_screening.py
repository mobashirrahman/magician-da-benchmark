#!/usr/bin/env python3
"""Generate matrix screening bundles and run them through the matrix-only pipeline.

  python tools/matrix_screening.py --designs baseline overdispersed --replicates 5
  python tools/matrix_screening.py --all --null-replicates 100 --spiked-replicates 30

Bundles are cheap: a design is a latent composition and Dirichlet-multinomial counts.
No FASTQ, assembly or binning catalogue is involved, so calibration replicates cost
only the differential abundance fits themselves.
"""
from pathlib import Path
import argparse
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from magician.config import load, resolve
from magician.screening import DESIGNS, build_bundle


def write_config(designs, null_replicates, spiked_replicates, bundle, methods, output, output_dir):
    """An overlay for matrix mode: the bundle plus the methods under comparison."""
    body = ["# Matrix screening overlay, generated by tools/matrix_screening.py.",
            "input_mode: matrix",
            f"matrix_input:\n  bundle: {bundle}",
            "analysis:",
            f"  methods: [{', '.join(methods)}]",
            "  metrics: [counts, relative]",
            "  min_total_count: 0",
            "  min_prevalence: 0.0",
            "  enable_status: [active, planned]",
            "  truth_reference: median_feature",
            f"storage:\n  budget_gb: 100",
            f"output_dir: {output_dir}",
            "experiment:",
            "  seeds: [42]",
            "  samples_per_group: 3",
            "genomes:\n  manifest: null"]
    Path(output).write_text("\n".join(body) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--designs", nargs="*", default=["baseline"],
                        choices=sorted(DESIGNS) + [], help="Screening designs to generate")
    parser.add_argument("--all", action="store_true", help="Every declared design")
    parser.add_argument("--null-replicates", type=int, default=2)
    parser.add_argument("--spiked-replicates", type=int, default=2)
    parser.add_argument("--first-seed", type=int, default=1000)
    parser.add_argument("--methods", nargs="*",
                        default=["wilcoxon_clr", "deseq2", "edger", "limma_voom", "aldex2", "ancombc2"])
    parser.add_argument("--bundle", default="cache/screening")
    parser.add_argument("--output-dir", default="results_screening")
    parser.add_argument("--config", default="cache/screening/config.yaml")
    parser.add_argument("--cores", type=int, default=8)
    parser.add_argument("--generate-only", action="store_true")
    parser.add_argument("--skip", nargs="*", default=[], help="Designs whose bundle already exists")
    args = parser.parse_args()
    designs = sorted(DESIGNS) if args.all else args.designs
    unknown = [name for name in designs if name not in DESIGNS]
    if unknown:
        parser.error(f"Unknown designs: {', '.join(unknown)}")
    bundle = resolve(args.bundle)
    todo = [name for name in designs if name not in args.skip]
    if todo:
        summary = build_bundle(todo, args.null_replicates, args.spiked_replicates,
                               bundle, args.first_seed)
        print(f"generated {len(summary)} replicates in {bundle}")
    write_config(designs, args.null_replicates, args.spiked_replicates,
                 str(bundle), args.methods, resolve(args.config), args.output_dir)
    print(f"wrote {resolve(args.config)}")
    if args.generate_only:
        return 0
    command = [sys.executable, str(ROOT / "run_magician.py"), "--configfile", str(resolve(args.config)),
               "--cores", str(args.cores)]
    return subprocess.call(command, cwd=str(ROOT))


if __name__ == "__main__":
    sys.exit(main())